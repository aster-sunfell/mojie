test('normal editing numbers real newlines and highlights the same number on wrapped continuations', async ({ page }) => {
  await mockWorkspace(page)
  await page.goto('/projects/p/chapters/c')
  const input = page.getByRole('textbox', { name: '章节正文', exact: true })
  await expect(input).toBeVisible()
  await page.evaluate(() => document.fonts.ready)
  const longLine = '林舟沿着山谷记录道路气候与树木的变化。'.repeat(7)
  await input.fill(`${longLine}\n第二行正文。`)
  const numbers = page.locator('.editorDocument .lineNumber')
  await expect(numbers).toHaveText(['1', '2'])
  const box = await input.boundingBox()
  const metrics = await input.evaluate(element => ({
    padding: parseFloat(getComputedStyle(element).paddingTop),
    lineHeight: parseFloat(getComputedStyle(element).lineHeight),
  }))
  await page.mouse.move(box.x + 40, box.y + metrics.padding + metrics.lineHeight * 1.5)
  await expect(page.locator('.hoveredLineNumber')).toHaveText('1')
  const second = await numbers.nth(1).boundingBox()
  expect(second.y - box.y).toBeGreaterThan(metrics.lineHeight * 2)
  await page.mouse.move(box.x + 40, second.y + second.height / 2)
  await expect(page.locator('.hoveredLineNumber')).toHaveText('2')
  await input.focus()
  await input.press('ControlOrMeta+End')
  await input.press('Enter')
  await input.pressSequentially('third line')
  await expect(numbers).toHaveText(['1', '2', '3'])
  await expect(input).toHaveValue(`${longLine}\n第二行正文。\nthird line`)
  await page.getByRole('button', { name: '保存正文', exact: true }).click()
  await expect(page.locator('.editorHeader')).toContainText('已保存')
  await page.reload()
  await expect(input).toHaveValue(`${longLine}\n第二行正文。\nthird line`)
  await expect(numbers).toHaveText(['1', '2', '3'])
})

test('desktop reading places the whole assistant to the right and preserves drafts in focus modes', async ({ page }) => {
  await mockWorkspace(page)
  await page.goto('/projects/p/chapters/c')
  const panel = page.getByRole('region', { name: '写作助手', exact: true })
  const input = page.getByRole('textbox', { name: '对话消息' })
  const editor = page.locator('.editorArea')
  await expect(page.locator('.conversationMessage.assistant')).toContainText('已核对人物设定')
  const panelBox = await panel.boundingBox(), editorBox = await editor.boundingBox()
  expect(panelBox.x).toBeGreaterThanOrEqual(editorBox.x + editorBox.width - 1)
  expect(Math.abs(panelBox.y - editorBox.y)).toBeLessThan(1)
  expect(Math.abs(panelBox.height - editorBox.height)).toBeLessThan(1)
  expect(panelBox.y + panelBox.height).toBeLessThanOrEqual(720)
  const composerBox = await page.getByRole('form', { name: '写作助手输入区' }).boundingBox()
  const messageBox = await page.locator('.messageList').boundingBox()
  expect(composerBox.x).toBeGreaterThan(panelBox.x)
  expect(composerBox.x + composerBox.width).toBeLessThanOrEqual(panelBox.x + panelBox.width)
  expect(Math.abs(composerBox.x - messageBox.x)).toBeLessThan(1)
  await expect(page.locator('.assistantResize,.assistantMessageToolbar')).toHaveCount(0)
  await page.locator('.editorArea').evaluate(element => { element.scrollTop = element.scrollHeight })
  expect((await panel.boundingBox()).y).toBe(panelBox.y)
  await input.fill(('检查经历与时间顺序。\n').repeat(20))
  expect((await input.boundingBox()).height).toBeLessThanOrEqual(120)
  await page.getByRole('button', { name: '专注章节', exact: true }).click()
  await expect(panel).toBeHidden()
  expect((await editor.boundingBox()).width).toBeGreaterThan(editorBox.width)
  await page.screenshot({ path: 'test-results/workspace-chapter-focus.png' })
  await page.getByRole('button', { name: '专注对话', exact: true }).click()
  await expect(editor).toBeHidden()
  await expect(input).toHaveValue(/检查经历/)
  expect((await panel.boundingBox()).width).toBeGreaterThan(panelBox.width)
  await page.screenshot({ path: 'test-results/workspace-conversation-focus.png' })
  await page.getByRole('button', { name: '并排阅读', exact: true }).click()
  await input.fill('继续分析人物动机')
  await page.screenshot({ path: 'test-results/workspace-desktop.png' })
})

for (const mobile of [false, true]) {
  test(`Markdown replies contain wide content on ${mobile ? 'mobile' : 'desktop'}`, async ({ page }) => {
    if (mobile) await page.setViewportSize({ width: 390, height: 844 })
    const longText = '核对人物经历与设定的一致性'.repeat(12)
    const analysis = '**简要分析：**\n\n第二章末句与人物设定存在明确冲突。\n\n'
      + '- **角色档案（林舟）**：林舟不会游泳。\n- 第一章设定：遇到急流会走桥。\n\n'
      + '> 建议安全走到对岸。\n\n'
      + `| 查阅来源 | 设定内容 |\n| --- | --- |\n| 人物档案 | ${longText} |\n\n`
      + `\`\`\`text\n${longText}\n\`\`\`\n\n`
      + `<https://example.com/${'long-path-'.repeat(30)}>`
    await mockWorkspace(page, { analysis }); await page.goto('/projects/p/chapters/c')
    if (mobile) await page.getByRole('button', { name: '专注对话', exact: true }).click()
    const result = page.locator('.conversationMessage.assistant')
    await expect(result.locator('strong').first()).toHaveText('简要分析：')
    await expect(result.getByRole('listitem')).toHaveCount(2)
    await expect(result.locator('blockquote')).toContainText('安全走到对岸')
    await expect(result.getByRole('table')).toHaveCount(1)
    expect(await result.locator('p').first().evaluate(element => getComputedStyle(element).whiteSpace)).toBe('normal')
    for (const scroll of [result.getByLabel('表格内容'), result.getByLabel('代码块')]) {
      expect(await scroll.evaluate(element => element.scrollWidth > element.clientWidth)).toBe(true)
      await scroll.evaluate(element => { element.scrollLeft = element.scrollWidth })
      expect(await scroll.evaluate(element => element.scrollLeft)).toBeGreaterThan(0)
    }
    expect(await result.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(mobile ? 390 : 1280)
  })
}

test('keyboard sending creates one conversation, accepts line breaks and permits drafting while running', async ({ page }) => {
  const state = await mockWorkspace(page, { history: false })
  await page.goto('/projects/p/chapters/c')
  const input = page.getByRole('textbox', { name: '对话消息' })
  await input.fill('核对人物经历'); await input.press('Shift+Enter'); await input.press('a')
  expect(state.writes).toHaveLength(0); expect(state.creates).toHaveLength(0)
  const content = await input.inputValue(); expect(content).toContain('\n')
  await input.press('Enter')
  await expect(page.getByRole('button', { name: '停止', exact: true })).toBeVisible()
  await expect(input).toHaveValue('')
  expect(state.creates).toHaveLength(1); expect(state.writes).toHaveLength(1)
  expect(state.writes[0]).toMatchObject({ contextChapterId: 'c', contextVersion: 3, content })
  await input.fill('下一轮追问'); await input.press('Enter'); expect(state.writes).toHaveLength(1)
  await page.getByRole('button', { name: '停止', exact: true }).click()
  await expect(page.getByRole('button', { name: '正在停止', exact: true })).toBeDisabled()
  expect(state.cancelled).toEqual(['active-1'])
})

