test('folding messages restores reading position and the height control supports keyboard and drag', async ({ page }) => {
  const analysis = Array.from({ length: 40 }, (_, index) => `第 ${index + 1} 项：检查人物经历、时间顺序与章节中的线索。`).join('\n\n')
  await mockWorkspace(page, { analysis }); await page.goto('/projects/p/chapters/c')
  const messages = page.locator('.conversationMessages'), panel = page.locator('.conversationPanel')
  await expect(page.locator('.conversationMessage.assistant')).toContainText('第 40 项')
  await messages.evaluate(element => { element.scrollTop = 40; element.dispatchEvent(new Event('scroll')) })
  await page.getByRole('button', { name: '收起消息' }).click()
  await page.getByRole('button', { name: '展开消息' }).click()
  await expect.poll(() => messages.evaluate(element => element.scrollTop)).toBe(40)
  const height = (await panel.boundingBox()).height
  const resize = page.getByRole('button', { name: '调整对话高度' })
  await resize.focus(); await resize.press('ArrowUp')
  await expect.poll(async () => (await panel.boundingBox()).height).toBeGreaterThan(height)
  const control = await resize.boundingBox(), grown = (await panel.boundingBox()).height
  await page.mouse.move(control.x + control.width / 2, control.y + control.height / 2)
  await page.mouse.down(); await page.mouse.move(control.x + control.width / 2, control.y + 45); await page.mouse.up()
  await expect.poll(async () => (await panel.boundingBox()).height).toBeLessThan(grown)
  await expect(page.getByRole('textbox', { name: '对话消息' })).toBeVisible()
})
