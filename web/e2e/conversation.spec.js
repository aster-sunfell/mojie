import { test, expect } from '@playwright/test'

test('persistent conversations isolate history and manage complete Skills', async ({ page, request }) => {
  const project = (await (await request.post('http://127.0.0.1:18080/api/v1/projects', { data: { title: `对话测试-${Date.now()}` } })).json()).data
  await page.goto(`/projects/${project.id}`)
  await page.getByRole('button', { name: '连续对话', exact: true }).click()
  await page.getByRole('button', { name: '新建对话', exact: true }).click()
  const select = page.getByRole('combobox', { name: '当前对话' })
  await expect(select).not.toHaveValue('')
  const first = await select.inputValue()
  await page.getByRole('textbox', { name: '对话消息' }).fill('记住林舟怕火')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(page.locator('.conversationMessages')).toContainText('林舟怕火，因此避开火光。')
  await page.getByRole('textbox', { name: '对话消息' }).fill('他为什么避开火光？')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(page.locator('.conversationMessage.assistant')).toHaveCount(2)
  await page.getByRole('button', { name: '新建对话', exact: true }).click()
  await expect(select).not.toHaveValue(first)
  const second = await select.inputValue()
  expect(second).not.toBe(first)
  await expect(page.locator('.conversationMessages')).not.toContainText('怕火')
  await page.getByRole('textbox', { name: '对话消息' }).fill('讨论大纲')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  await expect(page.locator('.conversationMessages')).toContainText('可以一起讨论大纲。')
  await select.selectOption(first)
  await expect(page.locator('.conversationMessage.assistant')).toHaveCount(2)
  await page.reload()
  await page.getByRole('button', { name: '连续对话', exact: true }).click()
  await expect(select).toHaveValue(first)
  await expect(page.locator('.conversationMessage.assistant')).toHaveCount(2)
  await page.getByRole('button', { name: 'Skill 库', exact: true }).click()
  const unique = `character-${Date.now()}`
  await page.locator('input[type=file][accept=".md,.zip"]').first().setInputFiles({ name: 'SKILL.md', mimeType: 'text/markdown', buffer: Buffer.from(`---\nname: ${unique}\ndescription: 人物检查\n---\n检查人物与章节。\n`) })
  await expect(page.locator('.skillDetail')).toContainText(unique)
  const card = page.locator('.skillCard').filter({ hasText: unique })
  await expect(card).toContainText('已停用')
  await card.getByRole('button', { name: '启用', exact: true }).click()
  await expect(card).toContainText('已启用')
  await page.getByRole('button', { name: 'SKILL.md', exact: true }).click()
  await expect(page.locator('.skillDetail')).toContainText('检查人物与章节。')
})
